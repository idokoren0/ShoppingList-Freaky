function t(key, vars = {}) {
  const dict = I18N[LANG] || I18N.en;
  const pick = (d) => (vars.n === 1 && d[`${key}_one`] != null ? d[`${key}_one`] : d[key]);
  let s = pick(dict) ?? pick(I18N.en) ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// Static text in index.html: data-i18n (text), data-i18n-placeholder, data-i18n-aria-label, data-i18n-alt, data-i18n-title
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  for (const attr of ['placeholder', 'aria-label', 'alt', 'title', 'content']) {
    const data = `data-i18n-${attr}`;
    root.querySelectorAll(`[${data}]`).forEach((el) => el.setAttribute(attr, t(el.getAttribute(data))));
  }
}

function setLanguage(lang) {
  LANG = LANGS[lang] ? lang : 'en';
  const meta = LANGS[LANG];
  document.documentElement.lang = LANG;
  document.documentElement.dir = meta.dir;
  try { localStorage.setItem('lang', LANG); } catch { /* ignore */ }
  applyI18n();
  document.title = t('appTitle');
}
